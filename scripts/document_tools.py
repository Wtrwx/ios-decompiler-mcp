"""Generate the tool catalog from the same Pydantic models used by MCP."""
from pathlib import Path
from tempfile import TemporaryDirectory

from flex_mcp.app import Application
from flex_mcp.config import Settings
from flex_mcp.server import create_server

root = Path(__file__).resolve().parents[1]
with TemporaryDirectory() as temporary:
    app = Application(Settings(workspace=root, state_dir=Path(temporary)))
    try:
        create_server(app)
        lines = ["# MCP tools", "", "Generated by `scripts/document_tools.py`. The MCP `tools/list` response supplies",
            "the complete JSON input and output schemas. All tools return a consistent",
            "`ok`, `data`, `error`, `request_id`, `elapsed_ms` envelope. Inputs reject unknown fields.", "",
            "Names marked **mutation** may change instrumentation, local projects, or device state.",
            "Device installation, uploads, launch, termination, uninstall and manual rollback",
            "additionally require an exact local-operator approval. Observation hooks do not replace methods.", "",
            "| Tool | Required input fields | Purpose |", "| --- | --- | --- |"]
        for name, tool in sorted(app.tools.tools.items()):
            required = ", ".join(f"`{key}`" for key, value in tool.model.model_fields.items() if value.is_required()) or "none"
            kind = " **mutation**" if not tool.read_only else ""
            lines.append(f"| `{name}`{kind} | {required} | {tool.description} |")
        (root / "docs/TOOLS.md").write_text("\n".join(lines) + "\n")
        print(f"Documented {len(app.tools.tools)} tools")
    finally:
        app.registry.close()
